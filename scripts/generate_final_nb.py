                "class PointLSTM(nn.Module):\n",
                "    \"\"\"Identical to 03_lstm_experiments.ipynb - uses last hidden state for prediction.\"\"\"\n",
                "    def __init__(self, hidden_layer_size=64, num_layers=2, output_size=1):\n",
                "        super().__init__()\n",
                "        self.lstm = nn.LSTM(1, hidden_layer_size, num_layers, batch_first=True, dropout=0.2)\n",
                "        self.linear = nn.Linear(hidden_layer_size, output_size)\n",
                "    def forward(self, input_seq):\n",
                "        lstm_out, _ = self.lstm(input_seq)\n",
                "        return self.linear(lstm_out[:, -1, :])\n",
                "\n",
                "def train_model(model, train_loader, val_loader, epochs=50, lr=0.001, patience=5):\n",
                "    \"\"\"Training loop identical to 03_lstm_experiments.ipynb with early stopping.\"\"\"\n",
                "    model.to(device)\n",
                "    loss_function = nn.MSELoss()\n",
                "    optimizer = torch.optim.Adam(model.parameters(), lr=lr)\n",
                "    best_val_loss = float('inf')\n",
                "    early_stop_counter = 0\n",
                "    best_model_state = None\n",
                "    for i in range(epochs):\n",
                "        model.train()\n",
                "        for seq, labels in train_loader:\n",
                "            seq, labels = seq.to(device), labels.to(device)\n",
                "            optimizer.zero_grad()\n",
                "            y_pred = model(seq)\n",
                "            loss = loss_function(y_pred, labels.squeeze(-1) if labels.shape[-1] == 1 else labels)\n",
                "            loss.backward()\n",
                "            optimizer.step()\n",
                "        model.eval()\n",
                "        val_loss = 0\n",
                "        with torch.no_grad():\n",
                "            for seq, labels in val_loader:\n",
                "                seq, labels = seq.to(device), labels.to(device)\n",
                "                y_pred = model(seq)\n",
                "                val_loss += loss_function(y_pred, labels.squeeze(-1) if labels.shape[-1] == 1 else labels).item()\n",
                "        val_loss /= len(val_loader)\n",
                "        if val_loss < best_val_loss:\n",
                "            best_val_loss = val_loss\n",
                "            best_model_state = {k: v.clone() for k, v in model.state_dict().items()}\n",
                "            early_stop_counter = 0\n",
                "        else:\n",
                "            early_stop_counter += 1\n",
                "            if early_stop_counter >= patience:\n",
                "                break\n",
                "    model.load_state_dict(best_model_state)\n",
                "    return model\n",
                "\n",
                "def create_sequences(data, seq_length, pred_length):\n",
                "    xs, ys = [], []\n",
                "    for i in range(len(data) - seq_length - pred_length + 1):\n",
                "        xs.append(data[i : i + seq_length])\n",
                "        ys.append(data[i + seq_length : i + seq_length + pred_length])\n",
                "    return np.array(xs), np.array(ys)"
